import { build } from 'esbuild'
import { createServer } from 'node:http'
import { Store } from '../src/store.js'
import { Worker } from '../src/worker.js'
import { handler } from '../src/http.js'
import { dayOf } from '../src/domain.js'
import assert from 'node:assert/strict'

// Browser fixture uses the real HTTP/store modules, not mocked fetch responses.
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright-core')
const bundle = await build({ entryPoints: ['test/fixture.jsx'], bundle: true, write: false, jsx: 'automatic', loader: { '.css': 'text' }, format: 'iife' })
const store = new Store(':memory:'), today = dayOf(Date.now(), 'Asia/Shanghai')
store.note(today, '修复远程连接重试，完成回归测试。', '/workspace/dsh')
store.save(today, '# 今日概览\n\n完善插件兼容性与稳定性。\n\n## 工作进展\n\n### DSH 插件\n\n- **已完成**：修复远程重连，并检查桌面来源校验。\n- **进行中**：工作记录独立工作区，待真实环境验收。\n\n## 关键决定\n\n日报独立存储，按需整理，聊天不等待。\n\n## 后续事项\n\n- 在移动端和桌面端完成验收。', 0, [], false)
store.save(today, `${store.report(today).markdown}\n\n[依据:${store.records(today)[0].id}]\n\n<img src=x onerror="window.__unsafe=true">`, 1, [], false)
const worker = new Worker(store, {}), http = handler(store, worker, () => undefined, async () => [{ id: 'test-provider', models: [{ id: 'test-model', name: '测试模型' }] }])
const server = createServer((req, res) => {
  if (req.url.startsWith('/worklog-control/')) return http(req, res)
  if (req.url === '/fixture.js') return res.writeHead(200, { 'content-type': 'text/javascript; charset=utf-8' }).end(bundle.outputFiles[0].text)
  res.writeHead(200, { 'content-type': 'text/html; charset=utf-8' }).end('<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><style>html,body,#root{height:100%;margin:0}body{background:#edf0f2}body[data-ds-dark-theme]{background:#24282d}</style></head><body><div id="root"></div><script src="/fixture.js"></script></body></html>')
})
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  const errors = []; page.on('pageerror', e => errors.push(e.message))
  await page.goto(`http://127.0.0.1:${server.address().port}`)
  await page.getByRole('heading', { name: '今日概览' }).waitFor()
  await page.getByRole('link', { name: '查看依据' }).click()
  await page.getByRole('dialog').waitFor()
  await page.getByRole('heading', { name: '会话结论' }).waitFor()
  assert.equal(await page.evaluate(() => window.__unsafe), undefined)
  await page.keyboard.press('Escape')
  await page.screenshot({ path: '/tmp/worklog-desktop.png', fullPage: true })
  await page.getByRole('button', { name: '采集设置' }).click()
  await page.getByRole('dialog').waitFor()
  await page.getByLabel('启用工作素材采集').check()
  await page.getByRole('button', { name: '全部项目', exact: true }).click()
  await page.getByLabel('日报整理模型', { exact: true }).selectOption(JSON.stringify(['test-provider', 'test-model']))
  await page.getByRole('button', { name: '保存设置' }).click()
  await page.getByRole('dialog').waitFor({ state: 'hidden' })
  assert.equal(store.config().scope, 'all')
  assert.equal(store.config().model, 'test-model')
  await page.getByRole('button', { name: '采集设置' }).click()
  await page.getByRole('button', { name: '选择项目', exact: true }).click()
  await page.getByLabel('添加项目路径').fill('/manual/project')
  await page.getByRole('button', { name: '添加项目', exact: true }).click()
  await page.getByRole('button', { name: '保存设置' }).click()
  await page.getByRole('dialog').waitFor({ state: 'hidden' })
  assert.equal(store.config().scope, 'selected')
  assert.ok(store.config().projects.includes('/manual/project'))
  await page.getByRole('button', { name: '补记一条' }).click()
  await page.getByRole('textbox', { name: '记录实际完成的工作、决定或待办' }).fill('浏览器验收通过')
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await page.getByRole('dialog').waitFor({ state: 'hidden' })
  await page.waitForFunction(() => document.querySelectorAll('.wl-source').length === 2)
  await page.locator('.wl-source').last().locator('summary').click()
  await page.getByText('浏览器验收通过').waitFor()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: '/tmp/worklog-mobile.png', fullPage: true })
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  await page.getByRole('button', { name: '日期', exact: true }).click()
  await page.getByRole('dialog').waitFor()
  await page.keyboard.press('Escape')
  await page.getByRole('dialog').waitFor({ state: 'hidden' })
  await page.evaluate(() => document.body.setAttribute('data-ds-dark-theme', ''))
  await page.screenshot({ path: '/tmp/worklog-dark.png', fullPage: true })
  await page.setViewportSize({ width: 1024, height: 768 })
  await page.getByRole('button', { name: '采集设置' }).click()
  const bounds = await page.getByRole('dialog').boundingBox()
  assert.ok(bounds.x >= 0 && bounds.y >= 0 && bounds.x + bounds.width <= 1024)
  assert.deepEqual(errors, [])
  console.log('Browser smoke passed: desktop/mobile/dark/tablet, settings, notes, date dialog, no overflow or console errors')
} finally { await browser.close(); server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); await worker.close(); store.close() }
